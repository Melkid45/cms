// One-time generator: copies the website font files that next/font produced (Google Fonts woff2,
// same @font-face rules and size-adjusted fallbacks) into the CMS as self-hosted files:
//   admin/public/fonts/*.woff2, admin/public/fonts/site-fonts.<hash>.css (linked by app/site/layout.tsx;
//   a static file, so its url()s stay /fonts/... and match the preloads), admin/src/lib/builder/site-font-files.json
// Usage: npm run build, then node scripts/extract-site-fonts.mjs .next/static
import { readFileSync, writeFileSync, copyFileSync, mkdirSync, readdirSync, rmSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";
const stat = process.argv[2];
const admin = join(import.meta.dirname, "..");
const chunks = join(stat, "chunks");
const files = readdirSync(chunks).filter((f) => f.endsWith(".css")).map((f) => [f, readFileSync(join(chunks, f), "utf8")]);
const siteCss = files.find(([, c]) => c.includes("--font-cormorant"));
const rootCss = files.find(([, c]) => c.includes("--font-playfair:") && c.includes("--font-geist-mono"));
if (!siteCss || !rootCss) throw Error("font CSS not found");
console.log("site fonts:", siteCss[0], "root fonts:", rootCss[0]);
mkdirSync(join(admin, "public/fonts"), { recursive: true });
const faces = [], vars = {}, canvasVars = [], rootVars = [];
const take = (css, isRoot) => {
  for (const m of css.matchAll(/@font-face\{([^}]*)\}/g)) {
    const body = m[1];
    const family = body.match(/font-family:([^;]+)/)[1].replace(/"/g, "");
    if (family.startsWith("Geist Mono")) continue;
    const url = body.match(/url\(\.\.\/media\/([^)]+)\)/);
    let out = body;
    if (url) {
      copyFileSync(join(stat, "media", url[1]), join(admin, "public/fonts", url[1]));
      out = body.replace(`url(../media/${url[1]})`, `url(/fonts/${url[1]})`);
      faces.push({
        family,
        file: `/fonts/${url[1]}`,
        weight: body.match(/font-weight:([^;]+)/)?.[1] || "400",
        style: body.match(/font-style:([^;]+)/)?.[1] || "normal",
        range: body.match(/unicode-range:([^;]+)/)?.[1] || "",
      });
    }
    blocks.push(`@font-face{${out}}`);
  }
  for (const m of css.matchAll(/\.[\w-]+_variable\{(--[\w-]+):([^}]+)\}/g)) {
    if (m[1] === "--font-geist-mono") continue;
    vars[m[1]] = m[2].match(/"([^"]+)"/)[1];
    (isRoot ? rootVars : canvasVars).push(`${m[1]}:${m[2]}`);
  }
};
const blocks = [];
// Same order as the next/font stylesheets on the page before (root fonts first, then the website
// fonts): with two "Inter" sets (root Inter and the opsz Inter of the "inter" pair) the later wins.
take(rootCss[1], true);
take(siteCss[1], false);
const css = (
`/* Website fonts, self-hosted (generated by scripts/extract-site-fonts.mjs from the
   next/font output of components/builder/site-fonts.ts + the Inter/Playfair root fonts):
   the same Google Fonts files, @font-face rules and size-adjusted fallbacks, served from
   /fonts so public pages can preload the website's own pair (public-page.tsx). The editor
   keeps next/font (site-fonts.ts). Do not edit by hand: regenerate after changing fonts. */
${blocks.join("\n")}
:root{${rootVars.join(";")}}
.site-canvas{${canvasVars.join(";")}}
`);
for (const old of readdirSync(join(admin, "public/fonts")).filter((n) => n.startsWith("site-fonts.")))
  rmSync(join(admin, "public/fonts", old));
const cssFile = `/fonts/site-fonts.${createHash("sha256").update(css).digest("hex").slice(0, 10)}.css`;
writeFileSync(join(admin, "public", cssFile), css);
writeFileSync(join(admin, "src/lib/builder/site-font-files.json"), JSON.stringify({ css: cssFile, vars, faces }, null, 1) + "\n");
console.log("faces", faces.length, "vars", Object.keys(vars).length);
